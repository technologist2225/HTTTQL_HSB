import { McqOptionKey, McqQuestion } from '../types/exam';

type RawTuple = [
  number, // id (1001..1150)
  number, // chapter (1..6)
  string, // prompt
  [string, string, string, string, string], // A, B, C, D, E
  McqOptionKey, // correct option
];

function buildQuestions(rows: RawTuple[]): McqQuestion[] {
  const keys: McqOptionKey[] = ['a', 'b', 'c', 'd', 'e'];
  return rows.map(([id, chapter, prompt, opts, correctOption]) => ({
    id,
    type: 'mcq',
    chapter,
    prompt,
    options: opts.map((text, idx) => ({ key: keys[idx], text })),
    correctOption,
    points: 1,
  }));
}

