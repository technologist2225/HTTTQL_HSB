import {
  AnswerFlag,
  ExamQuestion,
  McqOptionKey,
  McqQuestion,
  ShortAnswerQuestion,
} from '../types/exam';

export type RawGtkdMcq = [
  number, // question number 1..245 (stored as id = 3000 + num)
  number, // group 1..4 (stored in chapter)
  string, // prompt
  [string, string, string, string], // a, b, c, d
  McqOptionKey, // correctOption ('a'|'b'|'c'|'d')
  AnswerFlag?, // optional 'inferred' (*) or 'conflict' (⚠)
  string?, // optional explanatory note
];

export function buildGtkdMcqList(rows: RawGtkdMcq[]): McqQuestion[] {
  const keys: McqOptionKey[] = ['a', 'b', 'c', 'd'];
  return rows.map(([num, group, prompt, opts, correctOption, answerFlag, note]) => ({
    id: 3000 + num,
    type: 'mcq',
    chapter: group,
    prompt,
    options: opts.map((text, idx) => ({ key: keys[idx], text })),
    correctOption,
    points: 1,
    ...(answerFlag ? { answerFlag } : {}),
    ...(note ? { note } : {}),
  }));
}

